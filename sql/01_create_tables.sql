-- Създаване на таблиците за система за управление на таксиметрова компания
-- Източник: предоставената документация на проекта.

CREATE TABLE Клиенти (
    client_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    име VARCHAR2(100),
    телефон VARCHAR2(20),
    имейл VARCHAR2(100),
    адрес VARCHAR2(200)
);

CREATE TABLE Шофьори (
    driver_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    име VARCHAR2(100),
    телефон VARCHAR2(20),
    дата_назначаване DATE,
    статус VARCHAR2(50)
);

CREATE TABLE Цени (
    tariff_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    описание VARCHAR2(100),
    цена_на_км NUMBER(6,2),
    начална_такса NUMBER(6,2),
    валидна_от DATE,
    валидна_до DATE
);

CREATE TABLE Автомобили (
    car_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    регистрационен_номер VARCHAR2(20),
    модел VARCHAR2(50),
    марка VARCHAR2(50),
    година NUMBER(4),
    тип_гориво VARCHAR2(20),
    driver_id NUMBER,
    CONSTRAINT fk_автомобили_шофьори FOREIGN KEY (driver_id) REFERENCES Шофьори(driver_id)
);

CREATE TABLE Маршрути (
    route_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    начален_адрес VARCHAR2(200),
    краен_адрес VARCHAR2(200),
    разстояние NUMBER(6,2),
    средна_продължителност NUMBER(5,2)
);

CREATE TABLE Поръчки (
    order_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id NUMBER,
    driver_id NUMBER,
    tariff_id NUMBER,
    route_id NUMBER,
    дата_и_час_на_поръчка TIMESTAMP,
    начален_адрес VARCHAR2(200),
    краен_адрес VARCHAR2(200),
    разстояние NUMBER(6,2),
    продължителност NUMBER(5,2),
    статус VARCHAR2(50),
    CONSTRAINT fk_поръчки_клиенти FOREIGN KEY (client_id) REFERENCES Клиенти(client_id),
    CONSTRAINT fk_поръчки_шофьори FOREIGN KEY (driver_id) REFERENCES Шофьори(driver_id),
    CONSTRAINT fk_поръчки_цени FOREIGN KEY (tariff_id) REFERENCES Цени(tariff_id),
    CONSTRAINT fk_поръчки_маршрути FOREIGN KEY (route_id) REFERENCES Маршрути(route_id)
);

CREATE TABLE Плащания (
    payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id NUMBER,
    начин_на_плащане VARCHAR2(30),
    сума NUMBER(10,2),
    дата_на_плащане DATE,
    CONSTRAINT fk_плащания_поръчки FOREIGN KEY (order_id) REFERENCES Поръчки(order_id)
);

CREATE TABLE Оценки_и_коментари (
    review_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id NUMBER,
    driver_id NUMBER,
    order_id NUMBER,
    оценка NUMBER(1),
    коментар VARCHAR2(500),
    дата DATE,
    CONSTRAINT fk_ревю_клиенти FOREIGN KEY (client_id) REFERENCES Клиенти(client_id),
    CONSTRAINT fk_ревю_шофьори FOREIGN KEY (driver_id) REFERENCES Шофьори(driver_id),
    CONSTRAINT fk_ревю_поръчки FOREIGN KEY (order_id) REFERENCES Поръчки(order_id)
);
